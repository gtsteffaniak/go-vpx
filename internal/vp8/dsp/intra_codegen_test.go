//go:build govpx_generate

package dsp

import (
	"fmt"
	"os"
	"strings"
	"testing"
)

// TestGenerateIntraSIMD derives quarter-weight sample selectors from the
// libvpx v1.16.0 scalar predictors. Each output is avg2, avg3 or a copy;
// their weights are exactly representable as four quarter samples.
func TestGenerateIntraSIMD(t *testing.T) {
	modes := []func([]byte, int, []byte, []byte, byte){
		func(d []byte, s int, a, l []byte, x byte) { intra4x4VEPredictScalar(d, s, a, x) },
		func(d []byte, s int, a, l []byte, x byte) { intra4x4HEPredictScalar(d, s, l, x) },
		func(d []byte, s int, a, l []byte, x byte) { intra4x4LDPredictScalar(d, s, a) },
		intra4x4RDPredictScalar, intra4x4VRPredictScalar,
		func(d []byte, s int, a, l []byte, x byte) { intra4x4VLPredictScalar(d, s, a) },
		intra4x4HDPredictScalar,
		func(d []byte, s int, a, l []byte, x byte) { intra4x4HUPredictScalar(d, s, l) },
	}
	var tables [8][4][16]byte
	for mode, fn := range modes {
		var used [16]int
		for sample := range 13 {
			var border [16]byte
			border[sample] = 128
			var out [16]byte
			fn(out[:], 4, border[:8], border[8:12], border[12])
			for p, v := range out {
				if v%32 != 0 {
					t.Fatal("unrepresentable weight")
				}
				for range int(v) / 32 {
					if used[p] >= 4 {
						t.Fatal("too many weights")
					}
					tables[mode][used[p]][p] = byte(sample)
					used[p]++
				}
			}
		}
		for _, n := range used {
			if n != 4 {
				t.Fatal("non-unit weight sum")
			}
		}
	}
	var out strings.Builder
	fmt.Fprintln(&out, "// Code generated by go test -tags govpx_generate -run TestGenerateIntraSIMD; DO NOT EDIT.")
	fmt.Fprintln(&out, "// libvpx v1.16.0 directional predictor selectors, in VE/HE/LD/RD/VR/VL/HD/HU order.")
	fmt.Fprintln(&out, "package dsp\n\nvar intra4Selectors = [8][4][16]byte{")
	for _, mode := range tables {
		fmt.Fprintln(&out, "{")
		for _, slot := range mode {
			fmt.Fprintf(&out, "%#v,\n", slot)
		}
		fmt.Fprintln(&out, "},")
	}
	fmt.Fprintln(&out, "}")
	if err := os.WriteFile("intra_selectors.go", []byte(out.String()), 0644); err != nil {
		t.Fatal(err)
	}
}
