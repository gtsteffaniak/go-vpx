//go:build ignore

// gensimd translates the codec's one-dimensional integer transform networks
// into four-lane Go SIMD networks. Run from the repository root with
// go run scripts/gensimd.go. The scalar implementations remain the oracle.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"strings"
)

var fs = token.NewFileSet()
var funcs = map[string]bool{}

func raw(n ast.Node) string {
	var b bytes.Buffer
	if err := format.Node(&b, fs, n); err != nil {
		panic(err)
	}
	return b.String()
}
func vec(e ast.Expr) string {
	switch v := e.(type) {
	case *ast.Ident:
		if strings.HasPrefix(v.Name, "fdctCospi") || strings.HasPrefix(v.Name, "fdctSinpi") || strings.HasPrefix(v.Name, "cospi") || strings.HasPrefix(v.Name, "sinpi") {
			return "archsimd.BroadcastInt32x4(" + v.Name + ")"
		}
		return v.Name
	case *ast.BasicLit:
		return "archsimd.BroadcastInt32x4(" + v.Value + ")"
	case *ast.IndexExpr:
		return raw(v)
	case *ast.SliceExpr:
		return raw(v)
	case *ast.ParenExpr:
		return "(" + vec(v.X) + ")"
	case *ast.UnaryExpr:
		if v.Op == token.SUB {
			return "archsimd.Int32x4{}.Sub(" + vec(v.X) + ")"
		}
		panic("unary " + raw(v))
	case *ast.BinaryExpr:
		m := map[token.Token]string{token.ADD: "Add", token.SUB: "Sub", token.MUL: "Mul", token.AND: "And", token.OR: "Or", token.XOR: "Xor"}[v.Op]
		if m != "" {
			return "(" + vec(v.X) + ")." + m + "(" + vec(v.Y) + ")"
		}
		if v.Op == token.SHR {
			return "(" + vec(v.X) + ").ShiftAllRight(" + raw(v.Y) + ")"
		}
		if v.Op == token.SHL {
			return "(" + vec(v.X) + ").ShiftAllLeft(" + raw(v.Y) + ")"
		}
		panic("binary " + raw(v))
	case *ast.CallExpr:
		name := raw(v.Fun)
		a := []string{}
		for _, x := range v.Args {
			a = append(a, vec(x))
		}
		switch name {
		case "int", "int32", "int64":
			return a[0]
		case "int16":
			return "vecWrap(" + a[0] + ")"
		case "fdctRoundShift", "dctConstRoundShift":
			return "vecRound(" + a[0] + ")"
		}
		if funcs[name] {
			name += "Vec"
		}
		return name + "(" + strings.Join(a, ",") + ")"
	default:
		panic(fmt.Sprintf("expr %T %s", e, raw(e)))
	}
}
func stmt(s ast.Stmt) string {
	switch v := s.(type) {
	case *ast.AssignStmt:
		lhs := []string{}
		rhs := []string{}
		for _, x := range v.Lhs {
			lhs = append(lhs, raw(x))
		}
		for _, x := range v.Rhs {
			rhs = append(rhs, vec(x))
		}
		if v.Tok != token.ASSIGN && v.Tok != token.DEFINE {
			m := map[token.Token]string{token.ADD_ASSIGN: "Add", token.SUB_ASSIGN: "Sub"}[v.Tok]
			if m == "" {
				panic(raw(v))
			}
			return lhs[0] + " = " + lhs[0] + "." + m + "(" + rhs[0] + ")\n"
		}
		return strings.Join(lhs, ",") + " " + v.Tok.String() + " " + strings.Join(rhs, ",") + "\n"
	case *ast.DeclStmt:
		return strings.ReplaceAll(strings.ReplaceAll(strings.ReplaceAll(raw(v), "]int16", "]archsimd.Int32x4"), "]int32", "]archsimd.Int32x4"), "]int", "]archsimd.Int32x4") + "\n"
	case *ast.ExprStmt:
		return vec(v.X) + "\n"
	case *ast.IfStmt:
		// Zero-input fast exits save no work when other vector lanes are live.
		if strings.Contains(raw(v.Cond), "== 0") {
			return ""
		}
		panic("if " + raw(v))
	case *ast.RangeStmt:
		h := raw(v)
		h = h[:strings.Index(h, "{")]
		return h + block(v.Body)
	case *ast.ForStmt:
		h := raw(v)
		h = h[:strings.Index(h, "{")]
		return h + block(v.Body)
	case *ast.ReturnStmt:
		return "return\n"
	default:
		panic(fmt.Sprintf("stmt %T %s", s, raw(s)))
	}
}
func block(b *ast.BlockStmt) string {
	s := "{\n"
	for _, v := range b.List {
		s += stmt(v)
	}
	return s + "}\n"
}
func generate(pkg string, paths, names []string) {
	funcs = map[string]bool{}
	for _, n := range names {
		funcs[n] = true
	}
	out := "// Code generated by go run scripts/gensimd.go; DO NOT EDIT.\n// Four independent codec transforms per vector; int16 casts wrap exactly.\n//go:build goexperiment.simd && (arm64 || amd64) && !purego\n\npackage " + pkg + "\n\nimport \"simd/archsimd\"\n\n"
	for _, path := range paths {
		f, err := parser.ParseFile(fs, path, nil, 0)
		if err != nil {
			panic(err)
		}
		for _, d := range f.Decls {
			fn, ok := d.(*ast.FuncDecl)
			if !ok || !funcs[fn.Name.Name] {
				continue
			}
			args := []string{}
			for _, a := range fn.Type.Params.List {
				for _, n := range a.Names {
					args = append(args, n.Name+" []archsimd.Int32x4")
				}
			}
			out += "func " + fn.Name.Name + "Vec(" + strings.Join(args, ",") + ") " + block(fn.Body) + "\n"
		}
	}
	outPath := "internal/vp9/" + pkg + "/transform_network_simd.go"
	b, err := format.Source([]byte(out))
	if err != nil {
		os.WriteFile("/private/tmp/gensimd-error.go", []byte(out), 0644)
		panic(err)
	}
	if err = os.WriteFile(outPath, b, 0644); err != nil {
		panic(err)
	}
}
func main() {
	generate("encoder", []string{"internal/vp9/encoder/transform_quant.go"}, []string{"forwardDCT4", "forwardDCT8", "forwardDCT16", "forwardADST4", "forwardADST8", "forwardADST16"})
	generate("dsp", []string{"internal/vp9/dsp/idct4.go", "internal/vp9/dsp/idct8.go", "internal/vp9/dsp/idct16.go", "internal/vp9/dsp/idct32.go", "internal/vp9/dsp/iadst4.go", "internal/vp9/dsp/iadst8.go", "internal/vp9/dsp/iadst16.go"}, []string{"idct4", "idct8", "idct16", "idct32", "Iadst4", "iadst8", "iadst16"})
}
